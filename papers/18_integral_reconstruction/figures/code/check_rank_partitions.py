#!/usr/bin/env python3
"""Exact necessary Mukai inequalities, not an existence or compactness proof.

For NS perpendicular to H generated by D, D^2=-2K, a slope-zero simple
positive-rank factor (r,mD,s) satisfies s <= floor((1-K*m*m)/r).
The displayed coefficient bound is proved in R01, not guessed in a search.
"""
from fractions import Fraction
from itertools import combinations_with_replacement
from pathlib import Path
import json
import math


def admissible(K, R, M, S):
    # Each m_i^2 <= r_i*(R-S)/K <= R*(R-S)/K.
    bound = math.isqrt((R * (R - S)) // K)
    types = [(r, m, (1-K*m*m)//r)
             for r in range(1, R+1) for m in range(-bound, bound+1)]
    results = []

    def walk(start, rr, mm, ss, factors):
        if rr == R:
            if mm == M and ss >= S:
                results.append({'factors_at_max_s': factors,
                                'maximum_total_s': ss,
                                'maximum_lost_charge': ss-S})
            return
        for i in range(start, len(types)):
            r, m, s = types[i]
            if rr+r > R:
                break
            walk(i, rr+r, mm+m, ss+s, factors+[(r,m,s)])

    walk(0, 0, 0, 0, [])
    return {'K':K, 'total':(R,M,S), 'proved_abs_m_bound':bound,
            'admissible_partitions':results}


cases = {
    'rank7_spherical_a': admissible(22,3,1,-7),
    'rank7_auxiliary_w': admissible(22,4,1,-6),
    'rank7_main_v': admissible(22,7,2,-13),
    'rank5_failed_control_v': admissible(13,5,2,-11),
}
expected = {
    'rank7_spherical_a': {((3,1,-7),)},
    'rank7_auxiliary_w': {((4,1,-6),), ((1,0,1),(3,1,-7))},
    'rank7_main_v': {((7,2,-13),), ((3,1,-7),(4,1,-6)),
                    ((1,0,1),(3,1,-7),(3,1,-7))},
}
for name, want in expected.items():
    got = {tuple(map(tuple,x['factors_at_max_s']))
           for x in cases[name]['admissible_partitions']}
    assert got == want, (name, got, want)
    assert all(x['maximum_lost_charge']==0
               for x in cases[name]['admissible_partitions'])
assert any(x['maximum_lost_charge']==1
           for x in cases['rank5_failed_control_v']['admissible_partitions'])


def pair(x,y,K=22):
    r,m,s=x; R,M,S=y
    return -2*K*m*M-r*S-R*s

a,b,w,v=(3,1,-7),(1,0,1),(4,1,-6),(7,2,-13)
cases['mukai_pairings']={
    'a2':pair(a,a),'b2':pair(b,b),'a_b':pair(a,b),
    'w2':pair(w,w),'v2':pair(v,v),'a_w':pair(a,w),'a_v':pair(a,v),
}
assert list(cases['mukai_pairings'].values())==[-2,-2,4,4,6,2,0]
out=Path(__file__).with_name('rank_partitions.json')
out.write_text(json.dumps(cases,indent=2)+'\n')
print(json.dumps({'status':'PASS','scope':'exact necessary Mukai arithmetic only',
                  'output':str(out),
                  'candidate_partition_counts':{k:len(cases[k]['admissible_partitions'])
                                                for k in expected}}))
